import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import Ajv2020 from 'ajv/dist/2020.js';
import standalone from 'ajv/dist/standalone/index.js';

const base = new URL('../src/wallet-api/', import.meta.url);
const schemaText = readFileSync(new URL('schema/wallet-api-draft.schema.json', base), 'utf8');
const schema = JSON.parse(schemaText);
const registry = JSON.parse(readFileSync(new URL('schema/wallet-api-draft.methods.json', base), 'utf8'));
const digest = createHash('sha256').update(schemaText).digest('hex');
const symbol = name => name.replaceAll('-', 'Minus');
const check = process.argv.includes('--check');
function emit(path, content) {
  const url = new URL(path, base);
  if (check) { if (readFileSync(url, 'utf8') !== content) throw new Error(`stale generated wallet-api: ${path}`); }
  else writeFileSync(url, content);
}
const ajv = new Ajv2020({ strict: false, ownProperties: true, allErrors: false, inlineRefs: false, code: { source: true, esm: true } });
ajv.addSchema(schema);
const refs = Object.fromEntries(Object.keys(schema.$defs).map(name => [symbol(name), `${schema.$id}#/$defs/${name}`]));
let validators = standalone(ajv, refs);
const runtimeImports = new Map();
validators = validators.replace(/require\("([^"]+)"\)\.default/g, (_match, path) => {
  if (!runtimeImports.has(path)) runtimeImports.set(path, `runtime${runtimeImports.size}`);
  return `${runtimeImports.get(path)}Value`;
});
if (/\brequire\(/.test(validators)) throw new Error('unhandled standalone validator dependency');
const imports = [...runtimeImports].map(([path, name]) => `import * as ${name} from ${JSON.stringify(path + '.js')};\nconst ${name}Value = ${name}.default?.default ?? ${name}.default;`).join('\n');
emit('generated/validators.js', '// Generated by tools/generate-wallet-api.js; do not edit.\n' + imports + '\n' + validators + '\n');

function typeOf(s) {
  if (s === false) return 'never';
  if (s === true) return 'unknown';
  if (s.$ref) return symbol(s.$ref.split('/').at(-1));
  if ('const' in s) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map(value => JSON.stringify(value)).join(' | ');
  if (s.oneOf || s.anyOf) return '(' + (s.oneOf ?? s.anyOf).map(typeOf).join(' | ') + ')';
  if (Array.isArray(s.type)) return s.type.map(type => typeOf({ ...s, type })).join(' | ');
  if (s.type === 'object' || s.properties) {
    const required = new Set(s.required ?? []);
    const fields = Object.entries(s.properties ?? {}).map(([key, value]) => `${JSON.stringify(key)}${required.has(key) ? '' : '?'}: ${typeOf(value)};`);
    return '{ ' + fields.join(' ') + ' }';
  }
  if (s.type === 'array') return `Array<${typeOf(s.items ?? true)}>`;
  if (s.type === 'integer' || s.type === 'number') return 'number';
  if (['string', 'boolean', 'null'].includes(s.type)) return s.type;
  if (s.allOf) return s.allOf.map(typeOf).join(' & ');
  return 'unknown';
}
const definitions = Object.entries(schema.$defs).map(([name, definition]) => `export type ${symbol(name)} = ${typeOf(definition)};`).join('\n');
const methodMap = Object.entries(registry.methods).map(([method, row]) => `${JSON.stringify(method)}: { params: ${symbol(row.params.split('/').at(-1))}; result: ${symbol(row.result.split('/').at(-1))}; error: ${symbol(row.error.split('/').at(-1))} };`).join('\n');
emit('generated/types.d.ts', '// Generated DTO shapes; runtime validators also enforce conditional/semantic constraints.\n' + definitions + '\nexport interface WalletMethodMap {\n' + methodMap + '\n}\nexport type WalletMethod = keyof WalletMethodMap;\n');
emit('generated/registry.js', '// Generated; schema files in ../schema are the sole authoring source.\n' + `export const schemaDigest = ${JSON.stringify(digest)};\nexport const methodRegistry = ${JSON.stringify(registry.methods)};\nexport const contractRegistry = ${JSON.stringify(registry)};\n`);
const fixturesPath = new URL('schema/wallet-api-draft.examples.json', base);
const fixtures = JSON.parse(readFileSync(fixturesPath, 'utf8'));
for (const example of fixtures.cases) {
  if (example.valid && example.value?.result?.schemaDigest && example.value.result.schemaDigest !== digest) throw new Error('schema fixture digest is stale');
}
console.log(`wallet-api: ${Object.keys(refs).length} definitions, ${Object.keys(registry.methods).length} methods, digest ${digest}`);
